// Collects every translatable English string from the source into src/locales/keys.ts.
// Existing keys keep their position (translation files are arrays in this order); new ones are appended.
// Usage: node scripts/i18n-keys.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
const SRC = new URL('../src/', import.meta.url);
const unesc = (s) => s.replace(/\\'/g, "'").replace(/\\n/g, '\n').replace(/\\\\/g, '\\');
const found = []; const plural = {};
const add = (k) => { if (k && !found.includes(k)) found.push(k); };
for (const f of readdirSync(SRC)) {
  if (!/\.(ts|tsx)$/.test(f) || f === 'i18n.ts') continue;
  const s = readFileSync(new URL(f, SRC), 'utf8');
  // tp(count, 'one', 'other'): skip the count expression (it may contain nested brackets), then read the two strings.
  for (const m of s.matchAll(/\btp\(/g)) {
    let i = m.index + 3, depth = 0;
    for (; i < s.length; i++) { const c = s[i]; if ('([{'.includes(c)) depth++; else if (')]}'.includes(c)) depth--; else if (c === ',' && depth === 0) break; }
    const rest = s.slice(i + 1).match(/^\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'/);
    if (rest) { add(unesc(rest[2])); plural[unesc(rest[2])] = unesc(rest[1]); }
  }
  for (const m of s.matchAll(/\b(?:t|tt|tl|tr)\(\s*'((?:[^'\\]|\\.)*)'/g)) add(unesc(m[1]));
}
// Text that is translated through a variable rather than a literal.
const i18n = readFileSync(new URL('i18n.ts', SRC), 'utf8');
for (const m of i18n.matchAll(/cat_\w+: '([^']+)'/g)) add(m[1]);
for (const m of i18n.match(/DEFAULT_SUBS = new Set\(\[([\s\S]*?)\]\)/)[1].matchAll(/'([^']+)'/g)) add(m[1]);
for (const m of i18n.match(/DEFAULT_ACCOUNT_NAMES[^=]*= \{([^}]*)\}/)[1].matchAll(/'([^']+)'/g)) add(m[1]);
const app = readFileSync(new URL('App.tsx', SRC), 'utf8');
for (const m of app.match(/NAV_RAW[^=]*= \[([\s\S]*?)\];/)[1].matchAll(/\['\w+', '([^']+)'/g)) add(m[1]);
const views = readFileSync(new URL('views.tsx', SRC), 'utf8');
for (const m of views.match(/TYPE_LABEL = \{([^}]*)\}/)[1].matchAll(/'([^']+)'/g)) add(m[1]);
['weekly', 'monthly', 'yearly'].forEach(add);
// Flower themes: names and short descriptions first, then the field guide.
const fl = readFileSync(new URL('flowers.ts', SRC), 'utf8');
const field = (name) => [...fl.matchAll(new RegExp(`\\b${name}: '((?:[^'\\\\]|\\\\.)*)'`, 'g'))].map((m) => unesc(m[1]));
[...field('name'), ...field('blurb'), ...field('family')].forEach(add);
for (const block of fl.matchAll(/\{\s*\n\s*id: '[^']+'[\s\S]*?\n  \},/g)) {
  const b = block[0];
  for (const k of ['origin', 'where', 'season', 'meaning']) { const m = b.match(new RegExp(`\\b${k}: '((?:[^'\\\\]|\\\\.)*)'`)); if (m) add(unesc(m[1])); }
  const facts = b.match(/facts: \[([\s\S]*?)\],/);
  if (facts) for (const m of facts[1].matchAll(/'((?:[^'\\]|\\.)*)'/g)) add(unesc(m[1]));
}
const out = new URL('locales/keys.ts', SRC);
let keys = [];
if (existsSync(out)) keys = JSON.parse(readFileSync(out, 'utf8').match(/KEYS: string\[\] = (\[[\s\S]*?\]);/)[1]);
const fresh = found.filter((k) => !keys.includes(k));
const gone = keys.filter((k) => !found.includes(k));
keys = [...keys, ...fresh];
const plurals = Object.fromEntries(keys.filter((k) => plural[k]).map((k) => [k, plural[k]]));
writeFileSync(out, `// Generated by scripts/i18n-keys.mjs: every English string the app translates, in a fixed order.
// Translation files list their text in this same order. Plural keys are the English plural form;
// PLURAL_ONE gives the singular, and a translation may give {one, other, ...} forms for these.
export const KEYS: string[] = ${JSON.stringify(keys, null, 1)};
export const PLURAL_ONE: Record<string, string> = ${JSON.stringify(plurals, null, 1)};
`);
console.log(`${keys.length} keys (${fresh.length} new)${gone.length ? `; no longer used: ${gone.length}` : ''}`);
